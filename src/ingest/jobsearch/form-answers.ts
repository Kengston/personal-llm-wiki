/**
 * form-answers.ts — леджер готовых ответов на анкеты работодателей ([ADR-0035]).
 *
 * Файл `raw/jobsearch/form-answers.jsonl` завёлся раньше своей схемы: 46 записей писались
 * агентом руками, и проверить их было нечем. Схема появляется задним числом и описывает
 * ровно то, что в файле уже лежит, — не «как правильнее», а «как есть», иначе первая же
 * валидация объявила бы всю накопленную историю мусором.
 *
 * Две вещи, которые здесь неочевидны:
 *
 *   1. `source` — НЕ словарь. В записях лежат и пути к страницам хранилища
 *      (`wiki/capability-profile.md`), и человеческие формулировки («решение прогона»,
 *      «решение владельца»). Оба вида честные: ответ либо выведен из документа, либо
 *      принят как решение. Закрытый словарь пришлось бы натягивать на второй вид, а
 *      свободная строка сохраняет и путь, и решение без потери смысла.
 *
 *   2. `id` — slug вопроса, а не порядковый номер. Ответ ищется по смыслу («виза»,
 *      «уровень английского»), и человекочитаемый ключ — это то, что агент реально
 *      сопоставляет с полем формы. Дубли ключа означают, что ответ изменился: последняя
 *      строка выигрывает, как и в остальных леджерах подсистемы.
 */

import { z } from 'zod';

import { platformId } from './companies.js';

const isoDate = z.string().min(1);

export const FormAnswerRecordSchema = z.object({
	/** Slug вопроса: `visa-sponsorship`, `english-level-dropdown`. */
	id: z
		.string()
		.min(1)
		.max(64)
		.regex(/^[a-z0-9][a-z0-9_.-]*$/),
	/** Формулировка вопроса так, как её задаёт форма. */
	question: z.string().min(1).max(500),
	/** Готовый ответ — то, что подставляется в поле. */
	answer: z.string().min(1).max(2000),
	/** Дата первого использования: по ней видно, насколько ответ свежий. */
	first_used: isoDate,
	/** Откуда взят ответ: путь к странице хранилища или формулировка решения. */
	source: z.string().min(1).max(200),
	/** Оговорки к ответу: где он не подходит, что уточнить в разговоре. */
	note: z.string().max(1000).optional(),
	/**
	 * Площадка или ATS, чью анкету закрывает ответ ([ADR-0033]). Опционально: ответы вида
	 * «уровень английского» не привязаны ни к какой площадке и переиспользуются везде.
	 */
	platform: platformId.optional(),
});

export type FormAnswerRecord = z.infer<typeof FormAnswerRecordSchema>;
